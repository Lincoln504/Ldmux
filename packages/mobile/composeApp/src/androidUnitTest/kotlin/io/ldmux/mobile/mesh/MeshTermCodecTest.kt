    @Test
    fun theScriptedSessionLeavesTheMirrorExactlyWhereRustsMirrorWas() {
        val mirror = RowMirror()
        val d = TermDecoder()
        for ((n, step) in fixture["script"]!!.jsonArray.withIndex()) {
            val o = step.jsonObject
            // The stream is re-chunked at the record payload size, as the ARQ would deliver it.
            val bytes = unhex(o["stream"]!!.jsonPrimitive.content)
            val items = ArrayList<TermItem>()
            var i = 0
            while (i < bytes.size) { items += d.push(bytes.copyOfRange(i, minOf(bytes.size, i + MeshTerm.RECORD_PAYLOAD))); i += MeshTerm.RECORD_PAYLOAD }
            assertEquals<List<TermItem>>(o["messages"]!!.jsonArray.map { TermItem.Message(message(it)) }, items, "step $n messages")
            for (it in items) mirror.apply((it as TermItem.Message).message)
            val want = o["mirror"]!!.jsonObject
            assertEquals((want["lines"] as JsonArray).map { it.jsonPrimitive.content }, mirror.lines, "step $n lines")
            assertEquals(want["cursorX"]!!.jsonPrimitive.int, mirror.cursorX)
            assertEquals(want["cursorY"]!!.jsonPrimitive.int, mirror.cursorY)
            assertEquals(want["flags"]!!.jsonPrimitive.int, mirror.flags)
            assertEquals(want["epoch"]!!.jsonPrimitive.int, mirror.epoch)
            val pr = want["profile"]!!.jsonObject
            assertEquals(RowMirror.ProfileInfo(pr["cols"]!!.jsonPrimitive.int, pr["rows"]!!.jsonPrimitive.int, pr["unsupported"]!!.jsonPrimitive.int), mirror.profile)
        }
    }

    @Test
    fun rowsHeldUntilCommitAndAStaleEpochIsNotApplied() {
        val m = RowMirror()
        m.apply(TermMessage.Profile(1, 10, 1, 0))
        assertTrue(!m.apply(TermMessage.Rows(5, false, listOf(TermPatch(0, false, "stale")))))
        assertEquals(listOf(""), m.lines, "rows are held, not painted")
        assertTrue(m.apply(TermMessage.Commit(6, 0, 0, 0)))
        assertEquals(listOf(""), m.lines)
        assertNull(m.closed)
        m.apply(TermMessage.Closed(MeshTerm.Closed.EXITED))
        assertEquals(MeshTerm.Closed.EXITED, m.closed)
    }

