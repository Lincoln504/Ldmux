/**
 * The Kotlin port of the mesh terminal profile against vectors the *Rust* encoder wrote
 * (`crates/protocol/test/fixtures/mesh-term-vectors.json`, generated by
 * `mesh_term_fixture_matches_the_encoder`). Nothing here is hand-copied from the port, so a
 * change on either side that is not made on the other fails one suite.
 */
class MeshTermCodecTest {
    private val fixture: JsonObject by lazy {
        val f = File("../../../crates/protocol/test/fixtures/mesh-term-vectors.json")
        assertTrue(f.exists(), "the shared fixture is missing: ${f.absolutePath}")
        Json.parseToJsonElement(f.readText()).jsonObject
    }

    private fun unhex(s: String) = ByteArray(s.length / 2) { s.substring(it * 2, it * 2 + 2).toInt(16).toByte() }
    private fun hex(b: ByteArray) = b.joinToString("") { (it.toInt() and 0xff).toString(16).padStart(2, '0') }

    private fun message(j: JsonElement): TermMessage {
        val o = j.jsonObject
        fun i(k: String) = o[k]!!.jsonPrimitive.int
        return when (val kind = o["kind"]!!.jsonPrimitive.content) {
            "attach" -> TermMessage.Attach(i("version"), o["selector"]!!.jsonPrimitive.content)
            "input" -> TermMessage.Input(unhex(o["bytes"]!!.jsonPrimitive.content))
            "resync" -> TermMessage.Resync
            "detach" -> TermMessage.Detach
            "profile" -> TermMessage.Profile(i("version"), i("cols"), i("rows"), i("unsupported"), o["shell"]!!.jsonPrimitive.content)
            "resize" -> TermMessage.Resize(i("cols"), i("rows"))
            "key" -> TermMessage.Key(o["names"]!!.jsonArray.map { it.jsonPrimitive.content })
            "rows" -> TermMessage.Rows(
                i("epoch"), o["full"]!!.jsonPrimitive.boolean,
                o["patches"]!!.jsonArray.map {
                    val p = it.jsonObject
                    TermPatch(p["y"]!!.jsonPrimitive.int, p["append"]!!.jsonPrimitive.boolean, p["text"]!!.jsonPrimitive.content)
                },
            )
            "commit" -> TermMessage.Commit(i("epoch"), i("cursorX"), i("cursorY"), i("flags"))
            "closed" -> TermMessage.Closed(i("reason"))
            "list" -> TermMessage.ListRequest
            "sessions" -> TermMessage.Sessions(
                o["last"]!!.jsonPrimitive.boolean,
                o["entries"]!!.jsonArray.map {
                    SessionEntry(it.jsonObject["id"]!!.jsonPrimitive.content, it.jsonObject["label"]!!.jsonPrimitive.content)
                },
            )
            else -> error("unknown fixture kind $kind")
        }
    }

    private fun decodeAll(bytes: ByteArray): List<TermItem> = TermDecoder().push(bytes)

    @Test
    fun theLimitsAreTheHostsLimits() {
        val l = fixture["limits"]!!.jsonObject
        fun n(k: String) = l[k]!!.jsonPrimitive.int
        assertEquals(n("maxBody"), MeshTerm.MAX_BODY)
        assertEquals(n("maxInput"), MeshTerm.MAX_INPUT)
        assertEquals(n("maxSegment"), MeshTerm.MAX_SEGMENT)
        assertEquals(n("maxSelector"), MeshTerm.MAX_SELECTOR)
        assertEquals(n("maxLabel"), MeshTerm.MAX_LABEL)
        assertEquals(n("maxSessions"), MeshTerm.MAX_SESSIONS)
        assertEquals(n("maxRowsBody"), MeshTerm.MAX_ROWS_BODY)
        assertEquals(n("maxMessage"), MeshTerm.MAX_MESSAGE)
        assertEquals(n("recordPayload"), MeshTerm.RECORD_PAYLOAD)
        assertEquals(n("maxBuffer"), MeshTerm.MAX_BUFFER)
        assertEquals(n("version"), MeshTerm.VERSION)
        assertEquals(n("minVersion"), MeshTerm.MIN_VERSION)
        assertEquals(n("maxKeys"), MeshTerm.MAX_KEYS)
        val all = with(MeshTerm.Unsupported) { SCROLLBACK or STYLE or HYPERLINKS or MOUSE or IMAGES or RESIZE or CLIPBOARD }
        assertEquals(n("unsupportedAllV1"), all)
    }

    @Test
    fun everyMessageEncodesToExactlyTheBytesRustWrote() {
        val cases = fixture["messages"]!!.jsonArray
        assertTrue(cases.size >= 14)
        for (c in cases) {
            val m = message(c.jsonObject["message"]!!)
            assertEquals(c.jsonObject["hex"]!!.jsonPrimitive.content, hex(m.encode()), "encode $m")
        }
    }

    @Test
    fun everyRustMessageDecodesBackToTheSameMessage() {
        for (c in fixture["messages"]!!.jsonArray) {
            val want = message(c.jsonObject["message"]!!)
            val got = decodeAll(unhex(c.jsonObject["hex"]!!.jsonPrimitive.content))
            assertEquals(listOf<TermItem>(TermItem.Message(want)), got)
        }
    }

    @Test
    fun theHostsSessionPagesDecodeAndTheLastOneIsTheOnlyLastOne() {
        val pages = fixture["sessionPages"]!!.jsonObject["pages"]!!.jsonArray
        assertTrue(pages.size > 1, "the fixture must exercise a list spanning records")
        val d = TermDecoder()
        val got = ArrayList<TermMessage.Sessions>()
        for ((i, c) in pages.withIndex()) {
            val bytes = unhex(c.jsonObject["hex"]!!.jsonPrimitive.content)
            assertTrue(bytes.size <= MeshTerm.RECORD_PAYLOAD, "page $i is $bytes.size bytes")
            assertEquals(c.jsonObject["hex"]!!.jsonPrimitive.content, hex(message(c.jsonObject["message"]!!).encode()))
            for (item in d.push(bytes)) got += (item as TermItem.Message).message as TermMessage.Sessions
        }
        assertEquals(pages.size, got.size)
        assertEquals(List(got.size) { it == got.size - 1 }, got.map { it.last })
        val input = fixture["sessionPages"]!!.jsonObject["input"]!!.jsonArray.map { it.jsonObject["id"]!!.jsonPrimitive.content }
        assertEquals(input, got.flatMap { g -> g.entries.map { it.id } })
    }

    @Test
    fun brokenOrOversizeSessionsAreRefused() {
        assertFailsWith<TermEncodeException> {
            TermMessage.Sessions(true, listOf(SessionEntry("x".repeat(MeshTerm.MAX_SELECTOR + 1), ""))).encode()
        }
        assertFailsWith<TermEncodeException> {
            TermMessage.Sessions(true, listOf(SessionEntry("a", "y".repeat(MeshTerm.MAX_LABEL + 1)))).encode()
        }
        // an entry that claims 5 bytes of id with 1 following, and a List with a body
        val got = decodeAll(byteArrayOf(0x85.toByte(), 3, 1, 5, 'a'.code.toByte(), 0x05, 1, 0))
        assertEquals(listOf<TermItem>(TermItem.Malformed(0x85), TermItem.Malformed(0x05)), got)
    }

    @Test
    fun aKeyIsNamesWithOneSpaceBetweenAndNothingElse() {
        assertContentEquals(
            byteArrayOf(0x06, 0x06) + "Up C-c".encodeToByteArray(),
            TermMessage.Key(listOf("Up", "C-c")).encode(),
        )
        assertFailsWith<TermEncodeException> { TermMessage.Key(listOf("C c")).encode() }
        assertFailsWith<TermEncodeException> { TermMessage.Key(emptyList()).encode() }
        assertFailsWith<TermEncodeException> { TermMessage.Key(List(MeshTerm.MAX_KEYS + 1) { "Up" }).encode() }
        assertFailsWith<TermEncodeException> { TermMessage.Key(List(10) { "M-C-S-Left" }).encode() }
        // The decoder refuses the same, losing only that message.
        for (body in listOf("C c ", "", "Up  Down", "Up\u0001")) {
            val wire = byteArrayOf(0x06, body.length.toByte()) + body.encodeToByteArray()
            assertEquals(listOf<TermItem>(TermItem.Malformed(0x06)), decodeAll(wire), "[$body]")
        }
    }

    @Test
    fun aVersionOneProfileStillDecodesWithNoShellAndVersionTwoNamesIt() {
        val v1 = decodeAll(byteArrayOf(0x81.toByte(), 5, 1, 80, 24, 0x7f, 0))
        assertEquals(listOf<TermItem>(TermItem.Message(TermMessage.Profile(1, 80, 24, 0x7f, ""))), v1)
        val v2 = TermMessage.Profile(2, 80, 24, 0x7f, "ab12-1")
        assertEquals(listOf<TermItem>(TermItem.Message(v2)), decodeAll(v2.encode()))
        // A version-2 body whose shell length lies is malformed, never silently accepted.
        val lie = byteArrayOf(0x81.toByte(), 7, 2, 80, 24, 0x7f, 0, 9, 'a'.code.toByte())
        assertEquals(listOf<TermItem>(TermItem.Malformed(0x81)), decodeAll(lie))
        // A version-1 Profile carries no shell on the wire, whatever the object holds.
        assertEquals(7, TermMessage.Profile(1, 80, 24, 0x7f, "ignored").encode().size)
    }

    @Test
    fun aStreamSplitAnywhereDecodesTheSame() {
        val all = fixture["messages"]!!.jsonArray.map { it.jsonObject["hex"]!!.jsonPrimitive.content }
            .joinToString("").let(::unhex)
        val want = decodeAll(all)
        assertEquals(fixture["messages"]!!.jsonArray.size, want.size)
        for (chunk in listOf(1, 2, 3, 5, 7, 11, 144)) {
            val d = TermDecoder()
            val got = ArrayList<TermItem>()
            var i = 0
            while (i < all.size) { got += d.push(all.copyOfRange(i, minOf(all.size, i + chunk))); i += chunk }
            assertEquals(want, got, "chunk $chunk")
            assertEquals(0, d.buffered)
        }
    }

    @Test
    fun unknownTagIsSkippedMalformedCostsOneMessageOversizeIsFatal() {
        val s = fixture["streams"]!!.jsonObject
        val unknown = s["unknownTagSkipped"]!!.jsonObject
        assertEquals<List<TermItem>>(
            unknown["messages"]!!.jsonArray.map { TermItem.Message(message(it)) },
            decodeAll(unhex(unknown["hex"]!!.jsonPrimitive.content)),
        )
        val bad = s["malformedBodyCostsOneMessage"]!!.jsonObject
        val got = decodeAll(unhex(bad["hex"]!!.jsonPrimitive.content))
        assertEquals(2, got.size)
        assertEquals(TermItem.Malformed(0x83), got[0])
        assertEquals(TermItem.Message(TermMessage.Detach), got[1])
        val over = s["oversizeBody"]!!.jsonObject
        assertTrue(over["fatal"]!!.jsonPrimitive.boolean)
        val e = assertFailsWith<TermStreamException> { decodeAll(unhex(over["hex"]!!.jsonPrimitive.content)) }
        assertEquals(TermStreamException.Kind.BodyTooLong, e.kind)
    }

    @Test
    fun aGrowingUnfinishedStreamOverflowsInsteadOfGrowingForever() {
        val d = TermDecoder()
        val e = assertFailsWith<TermStreamException> { d.push(ByteArray(MeshTerm.MAX_BUFFER + 1)) }
        assertEquals(TermStreamException.Kind.Overflow, e.kind)
        assertEquals(0, d.buffered)
    }

    @Test
    fun theEncoderRefusesWhatTheWireCannotCarry() {
        assertFailsWith<TermEncodeException> { TermMessage.Input(ByteArray(0)).encode() }
        assertFailsWith<TermEncodeException> { TermMessage.Input(ByteArray(MeshTerm.MAX_INPUT + 1)).encode() }
        assertFailsWith<TermEncodeException> { TermMessage.Attach(MeshTerm.VERSION, "x".repeat(MeshTerm.MAX_SELECTOR + 1)).encode() }
        assertFailsWith<TermEncodeException> {
            TermMessage.Rows(1, false, listOf(TermPatch(0, false, "x".repeat(MeshTerm.MAX_SEGMENT + 1)))).encode()
        }
        assertFailsWith<TermEncodeException> { TermMessage.Commit(0x10000, 0, 0, 0).encode() }
        // The bounds themselves are accepted.
        TermMessage.Input(ByteArray(MeshTerm.MAX_INPUT)).encode()
        TermMessage.Attach(MeshTerm.VERSION, "x".repeat(MeshTerm.MAX_SELECTOR)).encode()
    }

    @Test
    fun everyInputMessageFitsOneRecordPayload() {
        assertTrue(TermMessage.Input(ByteArray(MeshTerm.MAX_INPUT)).encode().size <= MeshTerm.RECORD_PAYLOAD)
        assertTrue(MeshTerm.MAX_MESSAGE <= MeshTerm.RECORD_PAYLOAD)
    }

    @Test
    fun theScriptedSessionLeavesTheMirrorExactlyWhereRustsMirrorWas() {
        val mirror = RowMirror()
        val d = TermDecoder()
        for ((n, step) in fixture["script"]!!.jsonArray.withIndex()) {
            val o = step.jsonObject
            // The stream is re-chunked at the record payload size, as the ARQ would deliver it.
            val bytes = unhex(o["stream"]!!.jsonPrimitive.content)
            val items = ArrayList<TermItem>()
            var i = 0
            while (i < bytes.size) { items += d.push(bytes.copyOfRange(i, minOf(bytes.size, i + MeshTerm.RECORD_PAYLOAD))); i += MeshTerm.RECORD_PAYLOAD }
            assertEquals<List<TermItem>>(o["messages"]!!.jsonArray.map { TermItem.Message(message(it)) }, items, "step $n messages")
            for (it in items) mirror.apply((it as TermItem.Message).message)
            val want = o["mirror"]!!.jsonObject
            assertEquals((want["lines"] as JsonArray).map { it.jsonPrimitive.content }, mirror.lines, "step $n lines")
            assertEquals(want["cursorX"]!!.jsonPrimitive.int, mirror.cursorX)
            assertEquals(want["cursorY"]!!.jsonPrimitive.int, mirror.cursorY)
            assertEquals(want["flags"]!!.jsonPrimitive.int, mirror.flags)
            assertEquals(want["epoch"]!!.jsonPrimitive.int, mirror.epoch)
            val pr = want["profile"]!!.jsonObject
            assertEquals(RowMirror.ProfileInfo(pr["cols"]!!.jsonPrimitive.int, pr["rows"]!!.jsonPrimitive.int, pr["unsupported"]!!.jsonPrimitive.int), mirror.profile)
        }
    }

    @Test
    fun rowsHeldUntilCommitAndAStaleEpochIsNotApplied() {
        val m = RowMirror()
        m.apply(TermMessage.Profile(1, 10, 1, 0))
        assertTrue(!m.apply(TermMessage.Rows(5, false, listOf(TermPatch(0, false, "stale")))))
        assertEquals(listOf(""), m.lines, "rows are held, not painted")
        assertTrue(m.apply(TermMessage.Commit(6, 0, 0, 0)))
        assertEquals(listOf(""), m.lines)
        assertNull(m.closed)
        m.apply(TermMessage.Closed(MeshTerm.Closed.EXITED))
        assertEquals(MeshTerm.Closed.EXITED, m.closed)
    }

    @Test
    fun inputBytesKeepControlCharacters() {
        assertContentEquals(byteArrayOf(0x02, 0x01, 0x03), TermMessage.Input(byteArrayOf(3)).encode())
    }
}
