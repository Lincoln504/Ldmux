package io.ldmux.mobile.mesh

/**
 * **The preset dictionary a compressed frame may be deflated against.**
 *
 * A frame is a few hundred bytes of terminal text, and deflate's match finder has almost nothing to
 * work with at that size: the words a shell repeats (`crates/`, `cargo build`, `state    `,
 * `error: `, `$ `) appear once each, so they are coded literally. A dictionary turns them into short
 * back-references, and the gain is measured rather than assumed: a real 46x17 `ldmux mesh status`
 * screen goes from 419 bytes of plain deflate to **325** with it, which is the difference between
 * three records and two on a public-preset link, i.e. 0.6 s of air per full screen.
 *
 * **Hex, and pinned by the fixture, because it is a wire contract.** The host compresses against its
 * own copy of these bytes and this decoder inflates against this copy; if the two ever differ, every
 * frame fails to inflate. `MeshTermCodecTest` compares this constant with the fixture's
 * `frameDictionary.hex`, which the host's own test regenerates from its constant, so a drift on
 * either side fails a test on that side instead of blacking out the screen.
 */
