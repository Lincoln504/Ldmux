//! The L2 MeshMore gateway contract.
//!
//! This crate is the daemon's side of the tunnel that `docs/MESH-GATEWAY.md`
//! describes. It owns two things and nothing else:
//!
//!   * the frame format ([`frame`], [`messages`]), frozen byte for byte; and
//!   * a socket client ([`client`]) that speaks it over loopback.
//!
//! It deliberately contains **no radio knowledge**. No frequency, bandwidth,
//! spreading factor, coding rate, path hash, contact, channel or preset
//! arithmetic appears here. Records are opaque byte slices: the session layer
//! decides what they mean, and the MeshMore gateway decides how they reach the
//! air. A grep for `lora`, `spread`, `meshcore` or `airtime` in this crate
//! should find only comments explaining that absence.
//!
//! The Dart package `meshcore_gateway` is the reference implementation, and
//! `tests/vectors.rs` pins this port to byte strings generated by running it.

#![forbid(unsafe_code)]

pub mod client;
pub mod constants;
pub mod frame;
pub mod messages;

pub use client::{Handshake, MeshClient};
pub use constants::{
    BindError, CAP_RECV_CREDIT, CAP_STATUS_PUSH, CREDIT_WINDOW, CloseReason, DISCOVERY_RECORD_MAX,
    FrameType, HEADER_BYTES, HelloError, MAGIC, MAX_PAYLOAD, PAIRING_TOKEN_BYTES, PairError,
    RECORD_FLOOR, RECORD_MAX, RadioState, SendOutcome, UNKNOWN_BATTERY, UNKNOWN_RSSI, VERSION,
};
pub use frame::{Decoder, Frame, MeshError};
pub use messages::{BindOk, HelloOk, RecvRecord, SendResult, Status};
